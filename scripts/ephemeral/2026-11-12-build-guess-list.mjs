// 2026-11-12 — build app/src/game/words/guesses.ts from the ENABLE word list.
//
// Context: ADR-0001 QST-VALID-GUESSES answered B — answers are CS terms, but any
// real English five-letter word is an accepted guess. ENABLE (enable1.txt) is
// public domain (Debian scowl r/enable/README: "formally released into the
// Public Domain"). Source mirror used: github.com/dolph/dictionary enable1.txt.
//
// Usage: node scripts/ephemeral/2026-11-12-build-guess-list.mjs <path/to/enable1.txt>
// Writes: app/src/game/words/guesses.ts (one space-separated string, uppercase).
// Re-running is deterministic: same input file → byte-identical output.

import { readFileSync, writeFileSync } from 'node:fs'

const src = process.argv[2]
if (!src) {
  console.error('usage: node 2026-11-12-build-guess-list.mjs <enable1.txt>')
  process.exit(2)
}

const words = [
  ...new Set(
    readFileSync(src, 'utf8')
      .split(/\r?\n/)
      .map((w) => w.trim())
      .filter((w) => /^[a-z]{5}$/.test(w))
      .map((w) => w.toUpperCase()),
  ),
].sort()

const out = `// GENERATED by scripts/ephemeral/2026-11-12-build-guess-list.mjs — do not hand-edit.
// Five-letter words from the ENABLE word list (public domain), uppercased.
// Accepted as guesses alongside the CS answer list (ADR-0001, QST-VALID-GUESSES = B).
// ${words.length} words.
export const ENGLISH_GUESSES_RAW =
  '${words.join(' ')}'
`

writeFileSync(new URL('../../app/src/game/words/guesses.ts', import.meta.url), out)
console.log(`wrote ${words.length} words`)

// Outcome (2026-11-12): run once against enable1.txt (172,823 lines) →
// 10,173 five-letter words written to app/src/game/words/guesses.ts.
